// Command tree wiring for the Spec CLI's command surface (index, check,
// slug-exists, next-id, refs, links, feature, criterion, headings, list), per FEAT-SPEC-011 of
// specs/features/spec-index/spec-index-frd.md, the reference-integrity
// blueprint's CMD delta, the gherkin-adoption blueprint's EMIT delta, and
// the Command Surface component in specs/containers/spec-cli/spec-cli-container.md.
//
// Everything in this file is orchestration: it builds the cobra command
// tree, converts flags into calls against cli/core/corpus,
// cli/core/numbering and cli/core/finding, and renders their results as
// stdout and an exit status. No file in this package decides what makes a
// document valid, what a slug pattern is, or how a check is scored — that
// is the binding Change Guidance in spec-cli-container.md ("a check that
// lived here would be unavailable to a future API or MCP wrapper"). A
// capability that looks missing here belongs in cli/core or cli/profile,
// not in a workaround in this file.
//
// `--help` text is never written by hand: it is cobra's own rendering of
// the Use, Short and flag declarations below, so the declaration and the
// help text cannot drift (spec-cli-container.md's Change Guidance).
package cmd

import (
	"encoding/json"
	"fmt"
	"io"
	"path/filepath"

	"github.com/spf13/cobra"

	"github.com/brettcallaghan/agent-plugins/cli/core/corpus"
	"github.com/brettcallaghan/agent-plugins/cli/core/finding"
	"github.com/brettcallaghan/agent-plugins/cli/core/specmodel"
)

// ioStreams carries the two output streams a run writes to and the exit
// status a gate decided on.
//
// out is a buffer [execute] owns: it reaches the process's standard
// output only when the run ends 0 or 1, so a command never needs to hold
// back an answer in case it fails later.
//
// exitCode exists because a gate failing is not an error. A check run
// finding non-conformance is a successful run reporting a true fact, so
// its RunE returns nil and sets exitCode to statusGateFailed; a run
// ending 2, 3 or 4 returns a classified error instead (exit.go).
type ioStreams struct {
	out io.Writer
	err io.Writer
	// exitCode is the status a gate set. It starts at statusOK, the
	// correct status for every command that never sets it.
	exitCode int
	// entered is set when a RunE starts (see markEntry), so [execute] can
	// tell an error cobra raised while parsing the invocation from one a
	// command returned.
	entered bool
}

// newRootCmd builds the command tree: index, check, slug-exists, next-id,
// refs, links, feature, criterion, headings and list (AC-SPEC-011.1
// through AC-SPEC-011.5, AC-SPECREF-003.1 through AC-SPECREF-003.5,
// AC-SPECMD-005.1 through AC-SPECMD-005.10, AC-GHK-009.1,
// AC-SPECLIST-004.1). refs and links are the growth FEAT-SPEC-011
// anticipated; feature is the gherkin-adoption blueprint's EMIT delta;
// list is the corpus-listing blueprint's CMD delta. None renames or
// repurposes a subcommand another delta established.
//
// The root carries no Run of its own. Cobra's own default behavior for a
// command with subcommands and no Run — print the usage, which lists
// every subcommand with its one-line Short description — is exactly what
// AC-SPEC-011.5 asks for on a bare invocation or --help, so nothing here
// reimplements it.
func newRootCmd(streams *ioStreams) *cobra.Command {
	var configPath string

	root := &cobra.Command{
		Use:   "specs",
		Short: "Index and check a specification corpus",
		Long: "specs indexes a specification corpus and reports conformance findings " +
			"against the rules the active profile registers. Configuration is read " +
			"from the nearest specs.toml in the working directory or a directory " +
			"above it, searching up to the repository root, or from the file " +
			"--config names.",
		SilenceUsage: true,
		// Args is left unset (rather than cobra.NoArgs) precisely so a
		// bare invocation is accepted and falls through to the default
		// help-printing behavior described above, instead of being
		// rejected as an argument error.
	}
	// cobra's autogenerated `completion` command is no part of this
	// container's fixed subcommand vocabulary (FEAT-SPEC-011's rationale:
	// "later features... do not rename or repurpose the four established
	// here", and the reference-integrity blueprint's CMD delta grows that
	// vocabulary by exactly one, deliberately, rather than leaving room
	// for cobra's own addition), so it is turned off rather than left to
	// appear as an uncounted extra.
	root.CompletionOptions.DisableDefaultCmd = true
	// The default is empty, which means "discover": loadConfig searches
	// for the nearest specs.toml inside the command, never here, so help
	// and argument errors work in a directory holding none.
	root.PersistentFlags().StringVar(&configPath, "config", "",
		"path to specs.toml (default: the nearest specs.toml in the working "+
			"directory or above it, up to the repository root)")

	root.AddCommand(newIndexCmd(streams, &configPath))
	root.AddCommand(newCheckCmd(streams, &configPath))
	root.AddCommand(newSlugExistsCmd(streams, &configPath))
	root.AddCommand(newNextIDCmd(streams, &configPath))
	root.AddCommand(newRefsCmd(streams, &configPath))
	root.AddCommand(newLinksCmd(streams, &configPath))
	root.AddCommand(newFeatureCmd(streams, &configPath))
	root.AddCommand(newCriterionCmd(streams, &configPath))
	root.AddCommand(newHeadingsCmd(streams, &configPath))
	root.AddCommand(newListCmd(streams, &configPath))
	root.AddCommand(newC4Cmd(streams, &configPath))

	return root
}

// corpusOptions converts a resolved [Config] into the [corpus.Options] a
// build or open call needs.
//
// RepoRoot is derived from configPath's own directory rather than left
// empty: [corpus.Options.RepoRoot] defaults to the spec root when unset,
// which would report every path relative to the spec root rather than
// the repository root and violate AC-SPEC-009.8. specs.toml's directory
// is the repository root by definition (AC-SPEC-008.1), so this is
// resolution, not a policy decision this package is making on its own.
func corpusOptions(cfg *Config, configPath string) (corpus.Options, error) {
	absConfig, err := filepath.Abs(configPath)
	if err != nil {
		return corpus.Options{}, fmt.Errorf("resolving %s: %w", configPath, err)
	}
	return corpus.Options{
		RepoRoot:  filepath.Dir(absConfig),
		Root:      cfg.SpecRoot,
		Workspace: cfg.Workspace,
		Profile:   cfg.Profile,
	}, nil
}

// openCorpus opens the corpus for opts at the default index location,
// persisting the index when the open had to build one.
//
// The persisting is what makes AC-SPEC-010.5's own example true — "run
// twice in a row reads specs.json the second time". Until this existed
// only `specs index` ever wrote the artifact, so a workflow of checks and
// queries rebuilt from scratch every invocation and the warm path the
// FEAT-SPEC-009 budgets are stated against was never reached by the
// commands those budgets are about (`agent-plugins-9ur`).
//
// Writing is best-effort and its failure is discarded on purpose. A
// read-only checkout, a race with a concurrent writer, a full disk: none
// of them make the answer this command already computed any less
// correct, and a query that failed because it could not update a cache
// would be a worse tool than one that is merely slow. AC-SPEC-010.4's
// atomic replace is [corpus.Write]'s, so a concurrent reader never sees
// a partial file.
func openCorpus(opts corpus.Options) (*corpus.Corpus, error) {
	dest := corpus.IndexPath(opts, "")
	c, warm, err := corpus.Open(opts, dest)
	if err != nil {
		return nil, fmt.Errorf("opening the corpus: %w", err)
	}
	if !warm {
		_ = corpus.Write(c.Index(), dest, nil)
	}
	return c, nil
}

// renderReport writes a check run's answer — the generated
// [specmodel.FindingReport], its checks and findings — to streams.out as
// YAML, or as JSON when asJSON is set (AC-SPEC-006.5). One model, two
// syntaxes, so the two renderings carry the same values in the same
// order by construction ([[cli-output-standards]]).
func renderReport(streams *ioStreams, report *finding.Report, asJSON bool) error {
	model := report.Model()
	if asJSON {
		data, err := json.Marshal(model)
		if err != nil {
			return fmt.Errorf("rendering the finding report as JSON: %w", err)
		}
		fmt.Fprintf(streams.out, "%s\n", data)
		return nil
	}
	fmt.Fprint(streams.out, renderYAML(model))
	return nil
}

// reportConfigDefects writes specs.toml's findings to standard error and
// sets streams.exitCode to statusEnvironment.
//
// Every finding [Load] returns is a defect in the repository's own
// configuration — a schema violation, an unknown [profile].name, a
// registration defect — which the caller cannot fix by changing the
// invocation, so the run exits 3 and answers nothing. The findings go to
// standard error as text whatever --json says: standard error is not a
// structured channel, and [[cli-output-standards]] governs standard
// output only. They are still rendered through a [finding.Report], so
// their wording is the finding machinery's and not this package's.
func reportConfigDefects(streams *ioStreams, findings []specmodel.Finding) error {
	report := finding.NewReport()
	report.Add(findings...)
	fmt.Fprint(streams.err, report.Text())
	streams.exitCode = statusEnvironment
	return nil
}
